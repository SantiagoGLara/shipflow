-- ShipFlow: ampliacion del modelo de gestion y trazabilidad.
-- No modificar V1, V2 ni V3. PostgreSQL es la fuente de verdad.

-- Membresias y permisos dentro de cada proyecto.
CREATE TABLE project_members (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id BIGINT NOT NULL REFERENCES projects(id) ON DELETE CASCADE,
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
    role VARCHAR(30) NOT NULL,
    joined_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_project_members_project_user UNIQUE (project_id, user_id),
    CONSTRAINT uq_project_members_project_id_id UNIQUE (project_id, id),
    CONSTRAINT chk_project_members_role CHECK (role IN ('LEAD','DEVELOPER','REVIEWER','DEPLOYER'))
);
CREATE INDEX idx_project_members_user ON project_members(user_id);

-- El propietario actual de cada proyecto se convierte en LEAD.
INSERT INTO project_members (project_id, user_id, role)
SELECT id, owner_id, 'LEAD' FROM projects
ON CONFLICT (project_id, user_id) DO NOTHING;

-- Evolucion de tareas existentes sin perder sus datos.
ALTER TABLE tasks
    ADD COLUMN updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    ADD COLUMN priority VARCHAR(20) NOT NULL DEFAULT 'MEDIUM',
    ADD COLUMN due_date TIMESTAMPTZ,
    ADD COLUMN assignee_id BIGINT,
    ADD COLUMN created_by BIGINT REFERENCES users(id) ON DELETE SET NULL;
ALTER TABLE tasks
    ADD CONSTRAINT chk_tasks_priority CHECK (priority IN ('LOW','MEDIUM','HIGH','CRITICAL')),
    ADD CONSTRAINT fk_tasks_assignee_member FOREIGN KEY (project_id, assignee_id)
        REFERENCES project_members(project_id, user_id) ON DELETE SET NULL (assignee_id);
CREATE INDEX idx_tasks_assignee ON tasks(assignee_id);
CREATE INDEX idx_tasks_due_date ON tasks(due_date);

CREATE TABLE task_comments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    task_id BIGINT NOT NULL REFERENCES tasks(id) ON DELETE CASCADE,
    author_id BIGINT NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
    content TEXT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT chk_task_comments_content CHECK (length(trim(content)) > 0)
);
CREATE INDEX idx_task_comments_task_created ON task_comments(task_id, created_at);

CREATE TABLE task_reviews (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    task_id BIGINT NOT NULL REFERENCES tasks(id) ON DELETE CASCADE,
    reviewer_id BIGINT NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
    status VARCHAR(20) NOT NULL DEFAULT 'PENDING',
    summary TEXT,
    requested_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    resolved_at TIMESTAMPTZ,
    CONSTRAINT chk_task_reviews_status CHECK (status IN ('PENDING','APPROVED','CHANGES_REQUESTED'))
);
CREATE INDEX idx_task_reviews_task ON task_reviews(task_id);

CREATE TABLE defects (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id BIGINT NOT NULL REFERENCES projects(id) ON DELETE CASCADE,
    task_id BIGINT REFERENCES tasks(id) ON DELETE SET NULL,
    title VARCHAR(180) NOT NULL,
    description TEXT,
    severity VARCHAR(20) NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'OPEN',
    reported_by BIGINT NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
    assigned_to BIGINT REFERENCES users(id) ON DELETE SET NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    resolved_at TIMESTAMPTZ,
    CONSTRAINT chk_defects_severity CHECK (severity IN ('LOW','MEDIUM','HIGH','CRITICAL')),
    CONSTRAINT chk_defects_status CHECK (status IN ('OPEN','IN_PROGRESS','RESOLVED','CLOSED','REOPENED'))
);
CREATE INDEX idx_defects_project_status ON defects(project_id, status);
CREATE INDEX idx_defects_project_severity ON defects(project_id, severity);

CREATE TABLE test_runs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id BIGINT NOT NULL REFERENCES projects(id) ON DELETE CASCADE,
    version_label VARCHAR(80),
    executed_by BIGINT NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
    status VARCHAR(20) NOT NULL DEFAULT 'RUNNING',
    started_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    finished_at TIMESTAMPTZ,
    summary TEXT,
    CONSTRAINT chk_test_runs_status CHECK (status IN ('RUNNING','PASSED','FAILED','CANCELLED'))
);
CREATE INDEX idx_test_runs_project_started ON test_runs(project_id, started_at DESC);

CREATE TABLE test_results (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    test_run_id BIGINT NOT NULL REFERENCES test_runs(id) ON DELETE CASCADE,
    test_name VARCHAR(180) NOT NULL,
    status VARCHAR(20) NOT NULL,
    duration_ms BIGINT,
    details JSONB,
    executed_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT chk_test_results_status CHECK (status IN ('PASSED','FAILED','SKIPPED','ERROR')),
    CONSTRAINT chk_test_results_duration CHECK (duration_ms IS NULL OR duration_ms >= 0)
);
CREATE INDEX idx_test_results_run ON test_results(test_run_id);

CREATE TABLE releases (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id BIGINT NOT NULL REFERENCES projects(id) ON DELETE CASCADE,
    version VARCHAR(80) NOT NULL,
    description TEXT,
    status VARCHAR(24) NOT NULL DEFAULT 'DRAFT',
    created_by BIGINT NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    approved_at TIMESTAMPTZ,
    CONSTRAINT uq_releases_project_version UNIQUE (project_id, version),
    CONSTRAINT uq_releases_project_id_id UNIQUE (project_id, id),
    CONSTRAINT chk_releases_status CHECK (status IN ('DRAFT','IN_REVIEW','APPROVED','REJECTED','DEPLOYED','CANCELLED'))
);
CREATE INDEX idx_releases_project_status ON releases(project_id, status);

CREATE TABLE release_tasks (
    release_id BIGINT NOT NULL REFERENCES releases(id) ON DELETE CASCADE,
    task_id BIGINT NOT NULL REFERENCES tasks(id) ON DELETE RESTRICT,
    PRIMARY KEY (release_id, task_id)
);

CREATE TABLE release_approvals (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    release_id BIGINT NOT NULL REFERENCES releases(id) ON DELETE CASCADE,
    approver_id BIGINT NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
    status VARCHAR(20) NOT NULL,
    comment TEXT,
    decided_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT chk_release_approvals_status CHECK (status IN ('APPROVED','REJECTED'))
);
CREATE INDEX idx_release_approvals_release ON release_approvals(release_id);

CREATE TABLE environments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id BIGINT NOT NULL REFERENCES projects(id) ON DELETE CASCADE,
    name VARCHAR(80) NOT NULL,
    type VARCHAR(20) NOT NULL,
    base_url TEXT,
    active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_environments_project_name UNIQUE (project_id, name),
    CONSTRAINT uq_environments_project_id_id UNIQUE (project_id, id),
    CONSTRAINT chk_environments_type CHECK (type IN ('DEVELOPMENT','TESTING','STAGING','PRODUCTION'))
);

CREATE TABLE deployments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id BIGINT NOT NULL REFERENCES projects(id) ON DELETE CASCADE,
    release_id BIGINT NOT NULL,
    environment_id BIGINT NOT NULL,
    deployed_by BIGINT NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
    image_reference TEXT,
    status VARCHAR(20) NOT NULL DEFAULT 'PENDING',
    started_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    finished_at TIMESTAMPTZ,
    rollback_of BIGINT REFERENCES deployments(id) ON DELETE RESTRICT,
    result_summary TEXT,
    CONSTRAINT fk_deployments_release_project FOREIGN KEY (project_id, release_id)
        REFERENCES releases(project_id, id) ON DELETE RESTRICT,
    CONSTRAINT fk_deployments_environment_project FOREIGN KEY (project_id, environment_id)
        REFERENCES environments(project_id, id) ON DELETE RESTRICT,
    CONSTRAINT chk_deployments_status CHECK (status IN ('PENDING','RUNNING','SUCCEEDED','FAILED','ROLLED_BACK'))
);
CREATE INDEX idx_deployments_project_started ON deployments(project_id, started_at DESC);
CREATE INDEX idx_deployments_environment_status ON deployments(environment_id, status);

CREATE TABLE incidents (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id BIGINT NOT NULL REFERENCES projects(id) ON DELETE CASCADE,
    deployment_id BIGINT REFERENCES deployments(id) ON DELETE SET NULL,
    title VARCHAR(180) NOT NULL,
    description TEXT,
    severity VARCHAR(20) NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'OPEN',
    opened_by BIGINT NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
    assigned_to BIGINT REFERENCES users(id) ON DELETE SET NULL,
    opened_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    resolved_at TIMESTAMPTZ,
    CONSTRAINT chk_incidents_severity CHECK (severity IN ('LOW','MEDIUM','HIGH','CRITICAL')),
    CONSTRAINT chk_incidents_status CHECK (status IN ('OPEN','INVESTIGATING','MITIGATED','RESOLVED','CLOSED'))
);
CREATE INDEX idx_incidents_project_status ON incidents(project_id, status);

-- Auditoria relacional inmutable por convencion de aplicacion.
CREATE TABLE audit_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id BIGINT REFERENCES projects(id) ON DELETE SET NULL,
    actor_id BIGINT REFERENCES users(id) ON DELETE SET NULL,
    event_type VARCHAR(120) NOT NULL,
    aggregate_type VARCHAR(80) NOT NULL,
    aggregate_id VARCHAR(100) NOT NULL,
    payload JSONB NOT NULL DEFAULT '{}'::jsonb,
    occurred_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX idx_audit_events_project_time ON audit_events(project_id, occurred_at DESC);
CREATE INDEX idx_audit_events_aggregate ON audit_events(aggregate_type, aggregate_id);

-- Outbox: se inserta en la misma transaccion que el cambio de negocio.
CREATE TABLE outbox_events (
    id UUID PRIMARY KEY,
    aggregate_type VARCHAR(80) NOT NULL,
    aggregate_id VARCHAR(100) NOT NULL,
    event_type VARCHAR(120) NOT NULL,
    payload JSONB NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'PENDING',
    attempts INTEGER NOT NULL DEFAULT 0,
    next_attempt_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    processed_at TIMESTAMPTZ,
    last_error TEXT,
    CONSTRAINT chk_outbox_status CHECK (status IN ('PENDING','PROCESSING','PROCESSED','DEAD')),
    CONSTRAINT chk_outbox_attempts CHECK (attempts >= 0)
);
CREATE INDEX idx_outbox_pending ON outbox_events(status, next_attempt_at, created_at)
    WHERE status IN ('PENDING','PROCESSING');
